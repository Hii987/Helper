function setLang(code) {
  lang = code;
  document.documentElement.lang = code;
  try {
    localStorage.setItem("lang", code);
  } catch {}
}

function t(key, vars = {}) {
  return (STRINGS[lang][key] ?? key).replace(/\{(\w+)\}/g, (_, name) => vars[name]);
}
